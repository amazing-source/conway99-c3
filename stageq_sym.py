"""Stage Q with FULL symmetry breaking (research 2026-09-23).
Symmetries of a Stage-Q instance (F, sorted supports): permutations pi of the 6 triangles with pi(F) = F that map the support multiset to itself,
extended to the 27 independent orbits by an order-preserving matching of equal supports (sigma).  Such (pi, sigma) maps solutions to solutions.
Sound breaking: order all matrices by the row-major string of the FULL 33x33 matrix Q (rows/cols in index order, entry order 0<1<2 = bits (u,w)).
The lex-minimal element of a solution's orbit (under the group generated by these maps AND twin swaps) satisfies both the twin constraints of
quotient_model.add_lex_twins (their proof only uses the swap and minimality) and  string(Q) <= string(Q^sigma)  for every symmetry sigma.
Usage: python stageq_sym.py <instance name> [--relaxed]   (--relaxed drops all (independent x independent) Gram equations: a SAT control)"""
import json, sys, itertools, time
from quotient_model import QModel, add_lex_twins
from lean_encoding import build_cnf_lean


LEAN = True

def symmetries(edges, key, t=6):
    E = set(frozenset(e) for e in edges); out = []
    for pi in itertools.permutations(range(t)):
        if set(frozenset((pi[a], pi[b])) for a, b in edges) != E: continue
        img = [tuple(s[pi.index(i)] for i in range(t)) for s in key]       # support after relabelling triangles: new_s[pi[i]] = s[i]
        if sorted(img) != sorted(key): continue
        # order-preserving matching: k-th column with support x goes to the k-th column with support x in the sorted list
        pos = {}
        for Y, s in enumerate(key): pos.setdefault(s, []).append(Y)
        used = {s: 0 for s in pos}; sig = []
        for Y, s in enumerate(key):
            t_ = img[Y]; sig.append(pos[t_][used[t_]]); used[t_] += 1
        if list(pi) == list(range(t)) and sig == list(range(len(key))): continue
        out.append((list(pi), sig))
    return out

def build(inst, relaxed=False):
    F = {tuple(e) for e in inst["edges"]}; key = [tuple(s) for s in inst["support"]]
    types = ["T"] * 6 + ["I"] * 27; fixed = {}
    for i in range(6):
        for j in range(i + 1, 6): fixed[(i, j)] = int((i, j) in F)
    for Y, s in zip(range(6, 33), key):
        for i in range(6): fixed[(i, Y)] = s[i]
    QM = QModel(types, 14, fixed)
    if relaxed:
        gen = QM.constraints
        QM.constraints = lambda: (c for c in gen() if not (c[0][0] == "gram" and c[0][1] >= 6 and c[0][2] >= 6 and c[0][1] != c[0][2]))
    cls, pool = build_cnf_lean(QM) if LEAN else QM.build_cnf()     # lean = capped totalizers (validate_lean.py: PASS)
    groups = {}
    for Y, s in zip(range(6, 33), key): groups.setdefault(s, []).append(Y)
    add_lex_twins(QM, cls, pool, [g for g in groups.values() if len(g) > 1])
    return QM, cls, pool, key

def entry_bits(QM, pool, a, b):
    """list of literals/constants for Q[a][b] in bit order (u, w); constants as ('c', bit)."""
    if a == b: return [("c", 1), ("c", 1)] if QM.types[a] == "T" else [("c", 0), ("c", 0)]
    x, y = min(a, b), max(a, b)
    if (x, y) in QM.fixed:
        v = QM.fixed[(x, y)]; return [("c", int(v >= 1)), ("c", int(v == 2))]
    u = ("v", pool.id(("u", x, y)))
    w = ("v", pool.id(("w", x, y))) if QM.types[x] == "I" and QM.types[y] == "I" else ("c", 0)
    return [u, w]

def add_lex_leq(cls, pool, X, Y, tag):
    """string X <= string Y lexicographically; X, Y lists of ('v', lit) / ('c', 0|1)."""
    TRUE = pool.id(("TRUE",)); cls.append([TRUE])
    lit = lambda t: (TRUE if t[1] else -TRUE) if t[0] == "c" else t[1]
    e = pool.id(("glex", tag, 0)); cls.append([e])
    for k, (x, y) in enumerate(zip(X, Y)):
        a, b = lit(x), lit(y)
        if a == b: continue
        cls.append([-e, -a, b])
        e2 = pool.id(("glex", tag, k + 1))
        cls.append([-e, a, b, e2]); cls.append([-e, -a, -b, e2]); e = e2

def add_perm_lex(QM, cls, pool, full_perms):
    """for each permutation sigma of the m orbits (sigma[a] = image of a): string(Q) <=lex string(Q^sigma), Q^sigma[a][b] = Q[inv a][inv b]."""
    m = QM.m; order = [(a, b) for a in range(m) for b in range(m)]
    X = [t for (a, b) in order for t in entry_bits(QM, pool, a, b)]
    for n_, full in enumerate(full_perms):
        inv = [0] * m
        for a in range(m): inv[full[a]] = a
        Y = [t for (a, b) in order for t in entry_bits(QM, pool, inv[a], inv[b])]
        add_lex_leq(cls, pool, X, Y, n_)

def full_cnf(inst, relaxed=False):
    QM, cls, pool, key = build(inst, relaxed)
    syms = symmetries([tuple(e) for e in inst["edges"]], key)
    add_perm_lex(QM, cls, pool, [list(pi) + [6 + s for s in sig] for pi, sig in syms])   # sigma on all 33 orbits
    return QM, cls, pool, syms

def decode_check(inst, varmap, true_lits):
    """Independent of QModel: rebuild Q from the fixed data + (u, w) bits, check row sums and Q^2+Q = 12I+6J exactly."""
    F = {tuple(e) for e in inst["edges"]}; key = [tuple(s) for s in inst["support"]]
    Q = [[0] * 33 for _ in range(33)]
    for i in range(6):
        Q[i][i] = 2
        for j in range(6):
            if i != j and ((i, j) in F or (j, i) in F): Q[i][j] = 1
    for Y, s in enumerate(key):
        for i in range(6): Q[i][6 + Y] = Q[6 + Y][i] = s[i]
    for a in range(6, 33):
        for b in range(a + 1, 33):
            u = varmap.get("u,%d,%d" % (a, b)); w = varmap.get("w,%d,%d" % (a, b))
            Q[a][b] = Q[b][a] = (1 if u in true_lits else 0) + (1 if w in true_lits else 0)
    ok = all(sum(r) == 14 for r in Q) and all(sum(Q[a][k] * Q[k][b] for k in range(33)) + Q[a][b] == 12 * (a == b) + 6 for a in range(33) for b in range(33))
    return Q, ok

